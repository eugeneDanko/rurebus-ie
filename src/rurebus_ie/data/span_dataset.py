"""Tokenizer-aligned examples for span-based RuREBus NER.

The dataset stores only document windows and gold spans. Negative candidate
spans are generated by :class:`SpanClassificationCollator` at batching time so
the in-memory dataset stays compact.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterator, Mapping, Sequence

from .brat_parser import BratDocument, Entity
from .ner_dataset import load_documents_from_manifest
from .span_labels import SPAN_LABEL2ID


@dataclass(frozen=True)
class GoldTokenSpan:
    """One gold entity aligned to inclusive token boundaries."""

    start_token: int
    end_token: int
    label_id: int
    char_start: int
    char_end: int


@dataclass(frozen=True)
class TokenizedSpanExample:
    """One tokenizer window used to generate span candidates."""

    document_id: str
    window_id: int
    input_ids: tuple[int, ...]
    attention_mask: tuple[int, ...]
    offset_mapping: tuple[tuple[int, int], ...]
    word_ids: tuple[int | None, ...]
    gold_spans: tuple[GoldTokenSpan, ...]
    token_type_ids: tuple[int, ...] | None = None

    def __post_init__(self) -> None:
        lengths = {
            len(self.input_ids),
            len(self.attention_mask),
            len(self.offset_mapping),
            len(self.word_ids),
        }
        if self.token_type_ids is not None:
            lengths.add(len(self.token_type_ids))
        if len(lengths) != 1:
            raise ValueError("All token-level span fields must have equal length")


class RuReBusSpanDataset(Sequence[TokenizedSpanExample]):
    """A compact sequence of token windows plus document-level gold data."""

    def __init__(
        self,
        examples: Sequence[TokenizedSpanExample],
        documents: Sequence[BratDocument] = (),
        *,
        unrepresentable_entities: Sequence[tuple[str, str, int, int]] = (),
    ) -> None:
        self._examples = tuple(examples)
        self._document_texts = {document.document_id: document.text for document in documents}
        self._gold_entities = {
            document.document_id: tuple(
                (entity.entity_type, entity.start, entity.end, entity.text)
                for entity in document.entities
            )
            for document in documents
        }
        self._unrepresentable_entities = tuple(unrepresentable_entities)

    def __len__(self) -> int:
        return len(self._examples)

    def __getitem__(self, index: int) -> TokenizedSpanExample:
        return self._examples[index]

    def __iter__(self) -> Iterator[TokenizedSpanExample]:
        return iter(self._examples)

    @property
    def document_texts(self) -> Mapping[str, str]:
        return self._document_texts

    @property
    def gold_entities(self) -> Mapping[str, tuple[tuple[str, int, int, str], ...]]:
        return self._gold_entities

    @property
    def unrepresentable_entities(self) -> tuple[tuple[str, str, int, int], ...]:
        """Entities that cannot be formed with the configured token/width boundaries."""
        return self._unrepresentable_entities


def _validate_entities(document: BratDocument) -> tuple[Entity, ...]:
    entities = tuple(sorted(document.entities, key=lambda item: (item.start, item.end)))
    for entity in entities:
        if len(entity.spans) != 1:
            raise ValueError(
                f"{document.document_id}: discontinuous entity {entity.entity_id} "
                "is not supported by the contiguous Span NER model"
            )
        if entity.entity_type not in SPAN_LABEL2ID:
            raise ValueError(
                f"{document.document_id}: unsupported entity type {entity.entity_type!r}"
            )
    return entities


def _word_boundaries(
    word_ids: Sequence[int | None],
    offsets: Sequence[tuple[int, int]],
) -> tuple[tuple[int, int, int, int], ...]:
    """Return ``(start_token, end_token, char_start, char_end)`` per word."""
    boundaries: list[list[int]] = []
    previous_word_id: int | None = None
    for token_index, (word_id, (char_start, char_end)) in enumerate(zip(word_ids, offsets)):
        if word_id is None or char_start == char_end:
            previous_word_id = None
            continue
        if not boundaries or word_id != previous_word_id:
            boundaries.append([token_index, token_index, char_start, char_end])
        else:
            boundaries[-1][1] = token_index
            boundaries[-1][3] = char_end
        previous_word_id = word_id
    return tuple(tuple(item) for item in boundaries)


def build_span_examples(
    documents: Sequence[BratDocument],
    tokenizer: Any,
    *,
    max_length: int = 512,
    stride: int = 128,
    max_span_width: int = 32,
    strict_alignment: bool = False,
) -> RuReBusSpanDataset:
    """Tokenize BRAT documents and align gold entities to word-boundary spans."""
    if not getattr(tokenizer, "is_fast", False):
        raise ValueError("A fast tokenizer is required to obtain offsets and word ids")
    if max_length < 3:
        raise ValueError("max_length must leave room for text and special tokens")
    if not 0 <= stride < max_length:
        raise ValueError("stride must satisfy 0 <= stride < max_length")
    if max_span_width < 1:
        raise ValueError("max_span_width must be positive")

    examples: list[TokenizedSpanExample] = []
    represented: set[tuple[str, str, int, int]] = set()
    all_entities: set[tuple[str, str, int, int]] = set()

    for document in documents:
        entities = _validate_entities(document)
        all_entities.update(
            (document.document_id, entity.entity_type, entity.start, entity.end)
            for entity in entities
        )
        encoded = tokenizer(
            document.text,
            return_offsets_mapping=True,
            return_overflowing_tokens=True,
            truncation=True,
            max_length=max_length,
            stride=stride,
            padding=False,
        )
        for window_id in range(len(encoded["input_ids"])):
            offsets = tuple(
                (int(start), int(end))
                for start, end in encoded["offset_mapping"][window_id]
            )
            word_ids = tuple(encoded.word_ids(batch_index=window_id))
            boundaries = _word_boundaries(word_ids, offsets)
            by_start = {item[2]: (word_index, item) for word_index, item in enumerate(boundaries)}
            by_end = {item[3]: (word_index, item) for word_index, item in enumerate(boundaries)}
            gold_spans: list[GoldTokenSpan] = []
            for entity in entities:
                start_match = by_start.get(entity.start)
                end_match = by_end.get(entity.end)
                if start_match is None or end_match is None:
                    continue
                start_word, start_boundary = start_match
                end_word, end_boundary = end_match
                width = end_word - start_word + 1
                if width < 1 or width > max_span_width:
                    continue
                gold_spans.append(
                    GoldTokenSpan(
                        start_token=start_boundary[0],
                        end_token=end_boundary[1],
                        label_id=SPAN_LABEL2ID[entity.entity_type],
                        char_start=entity.start,
                        char_end=entity.end,
                    )
                )
                represented.add(
                    (document.document_id, entity.entity_type, entity.start, entity.end)
                )

            token_type_ids = encoded.get("token_type_ids")
            examples.append(
                TokenizedSpanExample(
                    document_id=document.document_id,
                    window_id=window_id,
                    input_ids=tuple(int(value) for value in encoded["input_ids"][window_id]),
                    attention_mask=tuple(
                        int(value) for value in encoded["attention_mask"][window_id]
                    ),
                    offset_mapping=offsets,
                    word_ids=word_ids,
                    gold_spans=tuple(gold_spans),
                    token_type_ids=(
                        tuple(int(value) for value in token_type_ids[window_id])
                        if token_type_ids is not None
                        else None
                    ),
                )
            )

    unrepresentable = tuple(sorted(all_entities - represented))
    if strict_alignment and unrepresentable:
        examples_text = ", ".join(str(item) for item in unrepresentable[:5])
        raise ValueError(
            f"{len(unrepresentable)} entities are not representable as configured spans. "
            f"Examples: {examples_text}"
        )
    return RuReBusSpanDataset(
        examples,
        documents,
        unrepresentable_entities=unrepresentable,
    )


def build_span_dataset_from_manifest(
    manifest_path: str | Path,
    split: str,
    tokenizer: Any,
    **tokenization_options: Any,
) -> RuReBusSpanDataset:
    documents = load_documents_from_manifest(manifest_path, split)
    return build_span_examples(documents, tokenizer, **tokenization_options)


